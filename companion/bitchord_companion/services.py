"""The companion's neighbours: Navidrome (rescan) and beets (config)."""
from __future__ import annotations

import hashlib
import json
import secrets
import shutil
import subprocess
import urllib.parse
import urllib.request
from pathlib import Path

from .config import Config


def navidrome_rescan(cfg: Config) -> str | None:
    """Asks Navidrome to scan now. Returns why it failed, or None.

    Uses the Subsonic `startScan` call, which needs an admin user. Without
    one configured the companion skips this and Navidrome picks the album up
    on its own scan or folder watcher.
    """
    salt = secrets.token_hex(6)
    token = hashlib.md5((cfg.navidrome_password + salt).encode()).hexdigest()
    query = urllib.parse.urlencode(
        {"u": cfg.navidrome_user, "t": token, "s": salt, "v": "1.16.1", "c": "bitchord-nd-companion", "f": "json"}
    )
    try:
        with urllib.request.urlopen(f"{cfg.navidrome_url}/rest/startScan?{query}", timeout=20) as r:
            body = json.loads(r.read().decode("utf-8", "replace"))
    except Exception as e:  # unreachable, not JSON, ...
        return str(e)
    response = body.get("subsonic-response", {})
    if response.get("status") != "ok":
        return (response.get("error") or {}).get("message", "Navidrome refused the scan")
    return None


def beets_plugins() -> list[str]:
    """Plugins for the generated config, limited to the ones this beets has.

    MusicBrainz matching is a plugin of its own in recent beets and built in
    before that; naming a plugin beets doesn't have stops every import, so
    each is checked.
    """
    wanted = ["musicbrainz", "fetchart", "embedart"]
    have = []
    for name in wanted:
        probe = subprocess.run(
            ["python", "-c", f"import beetsplug.{name}"], capture_output=True, text=True
        )
        if probe.returncode == 0:
            have.append(name)
    return have


def default_beets_config(cfg: Config, plugins: list[str]) -> str:
    beets_dir = cfg.config_dir / "beets"
    lines = [
        "# Generated by bitchord-nd-companion on first start. Edit freely:",
        "# it is only written when missing. Or set BEETS_CONFIG to your own.",
        f"directory: {cfg.music_dir}",
        f"library: {beets_dir / 'library.db'}",
        "import:",
        "  move: yes",
        "  write: yes",
        "  quiet: yes",
        "  # Not confident about a match? Keep the album with the tags it came",
        "  # with (title, artist, album, track numbers) rather than skipping it.",
        "  quiet_fallback: asis",
        "  duplicate_action: skip",
        f"  log: {beets_dir / 'import.log'}",
        "paths:",
        "  default: $albumartist/$album%aunique{}/$track $title",
        f"plugins: {' '.join(plugins)}" if plugins else "plugins: []",
    ]
    if "fetchart" in plugins:
        lines += [
            "fetchart:",
            "  sources: filesystem coverart itunes albumart",
            "  minwidth: 500",
        ]
    if "embedart" in plugins:
        lines += [
            "embedart:",
            "  auto: yes",
        ]
    return "\n".join(lines) + "\n"


def ensure_beets_config(cfg: Config) -> Path:
    if cfg.beets_config:
        return cfg.beets_config
    path = cfg.config_dir / "beets" / "config.yaml"
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(default_beets_config(cfg, beets_plugins()))
    return path


def tool_version(cmd: list[str]) -> str | None:
    if shutil.which(cmd[0]) is None:
        return None
    try:
        out = subprocess.run(cmd, capture_output=True, text=True, timeout=20).stdout.strip()
        return out.splitlines()[0] if out else None
    except Exception:
        return None
